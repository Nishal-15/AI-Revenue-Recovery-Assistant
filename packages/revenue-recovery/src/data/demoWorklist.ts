export const buildDemoWorklist = (now: number = Date.now()): WorklistItem[] =>
  SEEDS.map((seed) => ({
    id: seed.id,
    leakType: seed.leakType,
    patientName: seed.patientName,
    contactPhone: seed.contactPhone,
    reason: seed.reason,
    estimatedValue: seed.estimatedValue,
    priorityScore: seed.priorityScore,
    status: seed.status ?? "open",
    dueAt: hoursFrom(now, seed.dueInHours),
    snoozedUntil: seed.snoozedForHours === undefined ? null : hoursFrom(now, seed.snoozedForHours),
    resolvedAt: seed.resolvedHoursAgo === undefined ? null : hoursFrom(now, -seed.resolvedHoursAgo),
    resolutionNote: seed.resolutionNote ?? null,
  }));
